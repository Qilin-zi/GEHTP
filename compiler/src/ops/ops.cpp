    if (ops_registered) return;
    ops_registered = true;
    auto& reg = OpRegistry::instance();
        // Conv ops
        reg.register_op_fn("Conv", ConvOp::construct);
        // qnn-onnx-converter 产出的 op type 名为 "Conv2d"(见阶段1实测 net.json)
        reg.register_op_fn("Conv2d", ConvOp::construct);
